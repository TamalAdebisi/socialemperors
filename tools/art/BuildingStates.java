// Read visual timeline lengths only; never decompile the art's scripts.
// Compile with RenderSwf.java and FFDec (tools/ffdec.sh). Pass a text file
// listing building art names, one per line. stdout is buildingStates.ts;
// stderr lists unavailable source files. See docs/structure-idle-audit.md.
import com.jpexs.decompiler.flash.SWF;
import com.jpexs.decompiler.flash.tags.base.CharacterTag;
import com.jpexs.decompiler.flash.timeline.DepthState;
import com.jpexs.decompiler.flash.timeline.Frame;
import com.jpexs.decompiler.flash.timeline.Timeline;
import com.jpexs.decompiler.flash.timeline.Timelined;
import java.io.File;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.TreeMap;

public class BuildingStates {
    public static void main(String[] args) throws Exception {
        System.out.println("// Generated by tools/art/BuildingStates.java from the original art timelines.");
        System.out.println("// First child's state count for each facing; unlisted art has one state.");
        System.out.println("// This is visual metadata, not game code. See docs/structure-idle-audit.md.");
        System.out.println("export const BUILDING_STATES: Readonly<Record<string, readonly number[]>> = {");
        int read = 0, missing = 0, multiple = 0;
        for (String name : Files.readAllLines(Path.of(args[0])).stream().sorted().distinct().toList()) {
            try {
                SWF swf = RenderSwf.load(new File("assets/buildingsprites/" + name + ".swf"));
                Timeline root = ((Timelined) swf.getCharacterByClass(RenderSwf.findClass(swf, name))).getTimeline();
                List<Integer> counts = new ArrayList<>();
                for (Frame frame : root.getFrames()) {
                    // Flash's getChildAt(0): the first display layer, including shapes.
                    DepthState first = new TreeMap<>(frame.layers).values().stream().findFirst().orElse(null);
                    CharacterTag child = first == null ? null : first.getCharacter();
                    counts.add(child instanceof Timelined ? ((Timelined) child).getTimeline().getFrameCount() : 1);
                }
                read++;
                if (counts.stream().anyMatch(n -> n > 1)) {
                    multiple++;
                    System.out.println("  " + RenderSwf.jsonString(name) + ": " + counts + ",");
                }
            } catch (Exception error) {
                missing++;
                System.err.println(name + ": " + error);
            }
        }
        System.out.println("};");
        System.err.printf("Read %d; multiple states %d; unavailable %d%n", read, multiple, missing);
    }
}
